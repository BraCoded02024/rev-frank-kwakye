const { chromium } = require(process.env.JOURNEY_PLAYWRIGHT || 'playwright');
const fs = require('node:fs');
(async () => {
  fs.mkdirSync('docs/journey-preview', { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  await page.screenshot({ path: 'docs/journey-preview/prologue.png' });
  console.log('film', await page.locator('video').evaluate(v => ({ duration: v.duration, width: v.videoWidth, height: v.videoHeight })));
  const play = page.getByRole('button', { name: 'Play prologue' });
  if (await play.isVisible()) await play.click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: 'docs/journey-preview/film.png' });
  await page.getByRole('link', { name: 'Enter the calling' }).click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: 'docs/journey-preview/calling.png' });
  await page.mouse.wheel(0, 850);
  await page.waitForTimeout(1800);
  await page.screenshot({ path: 'docs/journey-preview/calling-deep.png' });
  console.log('film pauses offscreen', await page.locator('video').evaluate(v => v.paused));
  await page.locator('.journey-crossing').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: 'docs/journey-preview/threshold.png' });
  await page.getByRole('link', { name: 'Discover the foundations' }).click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: 'docs/journey-preview/formation.png' });
  console.log('desktop overflow', await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://localhost:3000/#calling', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1000);
  await page.screenshot({ path: 'docs/journey-preview/mobile.png' });
  console.log('mobile overflow', await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await page.screenshot({ path: 'docs/journey-preview/reduced.png' });
  console.log('reduced details', await page.locator('.calling-details').evaluate(el => getComputedStyle(el).opacity));
  await page.goto('http://localhost:3000/contact', { waitUntil: 'networkidle' });
  const skip = page.getByRole('button', { name: 'Skip', exact: true });
  if (await skip.isVisible()) await skip.click();
  await page.waitForTimeout(1200);
  console.log('contact available', await page.getByText('Ministry Invitations', { exact: true }).isVisible());
  console.log('errors', errors);
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
