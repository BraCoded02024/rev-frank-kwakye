const {chromium}=require(process.env.JOURNEY_PLAYWRIGHT || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
fs.mkdirSync('.checks',{recursive:true});
(async()=>{const browser=await chromium.launch({headless:true,channel:'msedge'});try{
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000/contact');
await page.getByRole('heading',{name:'An invitation to serve together.'}).waitFor();
assert.equal(await page.locator('.intro-gate, canvas, video').count(),0);
await page.screenshot({path:'.checks/invitation-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Send invitation',exact:true}).click();
assert.equal(await page.getByLabel('Your name',{exact:true}).evaluate(el=>el.validity.valueMissing),true);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.checks/invitation-mobile.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert(await page.locator('.invitation-form-card').evaluate(el=>el.getBoundingClientRect().top)<await page.locator('.invitation-aside').evaluate(el=>el.getBoundingClientRect().top));
await page.getByRole('link',{name:'Back to the journey'}).click();
await page.waitForSelector('.spatial-journey');
await page.getByRole('link',{name:'An invitation ↗',exact:true}).click();
await page.waitForSelector('.invitation-page');
assert.equal(await page.locator('.intro-gate, video, canvas').count(),0);
await page.getByRole('link',{name:'Back to the journey'}).click();
await page.waitForSelector('.spatial-journey');
await page.getByRole('navigation',{name:'Journey chapters'}).getByRole('button',{name:'Invitation'}).click();
await page.waitForSelector('.invitation-page');
assert.equal(await page.locator('.intro-gate, video, canvas').count(),0);
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto('http://localhost:3000/about');
await page.getByRole('button',{name:'Open menu'}).click();
await page.locator('.mobile-menu').getByRole('link',{name:'Contact'}).click();
await page.waitForSelector('.invitation-page');
assert.equal(await page.locator('.intro-gate, video, canvas').count(),0);
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: direct invitation, homepage header and chapter links, legacy contact navigation, no intro or canvas, required fields, mobile layout, no runtime errors. No form submitted.');
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1});
